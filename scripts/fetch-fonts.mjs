#!/usr/bin/env node
/* fetch-fonts.mjs — download the themes' fonts (Latin subset, woff2) from Google Fonts into
 * fonts/, with an @font-face sheet (fonts/fonts.css) pointing at the local files and each
 * family's SIL Open Font License. Run once, or again to refresh:  node scripts/fetch-fonts.mjs
 * The viewer serves these from its own site (font-src 'self'), so reading a link never
 * contacts Google; the file target still links Google Fonts directly. */
import { writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "fonts");
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/140.0 Safari/537.36";

// family → [Google css2 axis spec, file stem, license path in github.com/google/fonts]
const FAMILIES = {
  "Newsreader": ["ital,opsz,wght@0,6..72,400..700;1,6..72,400", "newsreader", "ofl/newsreader/OFL.txt"],
  "Source Serif 4": ["ital,opsz,wght@0,8..60,400..700;1,8..60,400", "source-serif-4", "ofl/sourceserif4/OFL.txt"],
  "Bricolage Grotesque": ["opsz,wght@12..96,400..800", "bricolage-grotesque", "ofl/bricolagegrotesque/OFL.txt"],
  "IBM Plex Sans": ["ital,wght@0,400..700;1,400", "ibm-plex-sans", "ofl/ibmplexsans/OFL.txt"],
  "IBM Plex Mono": ["wght@400;600;700", "ibm-plex-mono", "ofl/ibmplexmono/OFL.txt"],
};

mkdirSync(OUT, { recursive: true });
let sheet = "/* generated by scripts/fetch-fonts.mjs — Latin subsets, SIL Open Font License (see *.OFL.txt) */\n";
let total = 0;
for (const [family, [axes, stem, license]] of Object.entries(FAMILIES)) {
  const css = await (await fetch(`https://fonts.googleapis.com/css2?family=${family.replace(/ /g, "+")}:${axes}&display=swap`, { headers: { "user-agent": UA } })).text();
  const blocks = css.split("/* latin */").slice(1).map((b) => b.split("/*")[0]);
  for (const b of blocks) {
    const style = (b.match(/font-style:\s*(\w+)/) || [])[1] || "normal";
    const weight = (b.match(/font-weight:\s*([\d ]+)/) || [])[1].trim();
    const url = b.match(/url\((https:[^)]+\.woff2)\)/)[1];
    const range = b.match(/unicode-range:\s*([^;]+);/)[1].trim();
    const file = `${stem}${style === "italic" ? "-italic" : ""}${/ /.test(weight) ? "" : "-" + weight}.woff2`;
    const buf = Buffer.from(await (await fetch(url)).arrayBuffer());
    writeFileSync(join(OUT, file), buf);
    total += buf.length;
    sheet += `@font-face{font-family:"${family}";font-style:${style};font-weight:${weight};font-display:swap;src:url(fonts/${file}) format("woff2");unicode-range:${range}}\n`;
    console.log(`  ${file} ${buf.length.toLocaleString()} bytes`);
  }
  const lic = await (await fetch(`https://raw.githubusercontent.com/google/fonts/main/${license}`)).text();
  writeFileSync(join(OUT, `${stem}.OFL.txt`), lic);
}
writeFileSync(join(OUT, "fonts.css"), sheet);
console.log(`fonts/ — ${total.toLocaleString()} bytes of woff2, fonts.css, licenses`);
